// Turn `assets/agents_aura/` into the thumbnails the Agents grid serves, and into the typed module
// that names them.
//
// WHY THE DERIVED COPIES ARE COMMITTED RATHER THAN BUILT ON EVERY `npm run build`. The sources are
// photographs at up to a megabyte each; a card thumbnail is a few hundred pixels wide. Resizing at
// build time would mean an image dependency in `client/package.json` that exists to produce twenty-one
// files that never change, and a CI job that decodes 4MB of JPEG to emit the same bytes it emitted
// last time. So this runs by hand when the source set changes, and `test:agent-art` is what stops the
// output drifting from `lib/agentArt.ts` in between.
//
// THE NAMES ARE CANONICAL ON PURPOSE. §5.1 requires the mapping from an agent to a gradient to be
// deterministic and stable "on every replica, for every member of the workspace", and the index comes
// from sorting the filenames — so the filenames have to sort the same way everywhere. `aura-01.jpg`
// does; `WhatsApp Image 2026-08-18 at 4.32.4 PM (2).jpeg` sorts differently under different collation
// rules, and this project has already been bitten once by a platform-dependent path.
//
// Ordering is by the SOURCE filename, so re-running this against an unchanged directory reproduces
// the same assignment. Adding an image changes which agents get which gradient, which is acceptable
// (§5.1: wrapping is fine, there must always be a gradient) and is why the sources are kept.
//
//   node scripts/gen-agent-art.mjs        # needs Pillow: python -m pip install Pillow
//
// The resize itself is Python's, because that is what is on this machine and because a Node image
// library would be a dependency in the client's package.json for a script the client never runs.

import { execFileSync } from "node:child_process";
import { readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const CLIENT = join(HERE, "..");
const SOURCES = join(CLIENT, "..", "assets", "agents_aura");
const OUT = join(CLIENT, "public", "agent-art");

/** 800px wide, which is 2× the widest a comfortable-density card is ever drawn at. */
const WIDTH = 800;
const QUALITY = 82;

mkdirSync(OUT, { recursive: true });

const sources = readdirSync(SOURCES)
  .filter((f) => /\.(jpe?g|png|webp)$/i.test(f))
  .sort();
if (sources.length === 0) throw new Error(`no source images in ${SOURCES}`);

const script = `
import os, sys
from PIL import Image
src, dst, width, quality = sys.argv[1], sys.argv[2], int(sys.argv[3]), int(sys.argv[4])
names = sorted(f for f in os.listdir(src) if f.lower().endswith(('.jpg', '.jpeg', '.png', '.webp')))
for i, name in enumerate(names, start=1):
    im = Image.open(os.path.join(src, name)).convert('RGB')
    w, h = im.size
    if w > width:
        im = im.resize((width, max(1, round(h * width / w))), Image.LANCZOS)
    im.save(os.path.join(dst, 'aura-%02d.jpg' % i), 'JPEG', quality=quality, optimize=True, progressive=True)
`;
execFileSync("python", ["-c", script, SOURCES, OUT, String(WIDTH), String(QUALITY)], { stdio: "inherit" });

const files = sources.map((_, i) => `aura-${String(i + 1).padStart(2, "0")}.jpg`);
const list = files.map((f) => `  "${f}",`).join("\n");

writeFileSync(
  join(CLIENT, "src", "lib", "agentArtFiles.ts"),
  `// GENERATED by scripts/gen-agent-art.mjs. Do not edit by hand.
//
// The gradient thumbnails in \`public/agent-art/\`, sorted, as a typed list. §5.1 requires the list to
// be built at BUILD TIME rather than read from a directory at runtime — a browser cannot list a
// directory, and a server that could would be answering a question whose answer must be identical on
// every replica.
//
// SORTED EXPLICITLY, because the sort order IS the mapping: \`artFor\` hashes an agent's uuid to an
// index into this array, so a list in a different order is a different gradient for every agent in
// the workspace. Directory iteration order is not stable across platforms and this project has
// already been bitten once by a platform-dependent path.
//
// \`test:agent-art\` asserts this matches what is actually in \`public/agent-art\`.

export const AGENT_ART_FILES: readonly string[] = [
${list}
];
`,
);

console.log(`wrote ${files.length} thumbnails to public/agent-art and src/lib/agentArtFiles.ts`);
